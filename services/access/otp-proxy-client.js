const OTP_SERVICE_BASE_URL = String(
  process.env.CRM_OTP_BASE_URL || "https://api.findoly.com/otp",
).replace(/\/+$/, "");
const SEND_OTP_URL = process.env.CRM_OTP_SEND_URL || `${OTP_SERVICE_BASE_URL}/send-otp`;
const VERIFY_OTP_URL = process.env.CRM_OTP_VERIFY_URL || `${OTP_SERVICE_BASE_URL}/verify-otp`;
const REQUEST_TIMEOUT_MS = Math.min(
  Math.max(Number(process.env.CRM_OTP_REQUEST_TIMEOUT_MS || 12000) || 12000, 1000),
  60000,
);

async function requestOtpApi(url, payload) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);
  let requestStarted = false;
  try {
    requestStarted = true;
    const response = await fetch(url, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Accept: "application/json, text/plain;q=0.9, */*;q=0.8",
      },
      body: JSON.stringify(payload),
      signal: controller.signal,
    });

    const rawBody = await response.text().catch(() => "");
    let body = {};
    if (rawBody) {
      try {
        body = JSON.parse(rawBody);
      } catch (_error) {
        body = { message: rawBody.slice(0, 1000) };
      }
    }

    const upstreamStatus = String(
      body?.status || body?.data?.status || body?.result?.status || "",
    ).trim().toLowerCase();
    const explicitlyFailed = body?.success === false
      || body?.data?.success === false
      || ["error", "failed", "fail", "rejected", "invalid"].includes(upstreamStatus);

    if (!response.ok || explicitlyFailed) {
      const rawRetryAfter = body?.retryAfterSeconds
        || body?.retryAfter
        || body?.data?.retryAfterSeconds
        || response.headers.get("retry-after");
      const retryAfterSeconds = Number.isFinite(Number(rawRetryAfter))
        ? Math.max(1, Math.ceil(Number(rawRetryAfter)))
        : 0;
      let message = body?.message
        || body?.error
        || body?.data?.message
        || body?.result?.message
        || `OTP service request failed with status ${response.status}`;
      if (response.status === 429 && retryAfterSeconds > 0 && !/wait|second|minute/i.test(message)) {
        message = `Too many OTP requests. Please wait ${retryAfterSeconds} second${retryAfterSeconds === 1 ? "" : "s"} and try again.`;
      }
      const status = response.status === 429
        ? 429
        : response.status >= 400 && response.status < 500
          ? 400
          : 502;
      const error = Object.assign(new Error(String(message).slice(0, 1000)), {
        status,
        retryAfterSeconds,
        upstreamStatusCode: response.status,
        upstreamCode: body?.code || body?.data?.code || "",
        // A 5xx response may be generated by a gateway after the downstream
        // provider accepted the message. Verification remains authoritative.
        requestMayHaveSucceeded: response.status >= 500,
      });
      throw error;
    }
    return body;
  } catch (error) {
    if (error?.name === "AbortError") {
      throw Object.assign(new Error("OTP service did not respond in time"), {
        status: 504,
        requestMayHaveSucceeded: requestStarted,
      });
    }
    if (error?.status) throw error;
    throw Object.assign(new Error("Unable to connect to the OTP service"), {
      status: 502,
      requestMayHaveSucceeded: requestStarted,
      cause: error,
    });
  } finally {
    clearTimeout(timer);
  }
}

module.exports = {
  requestOtpApi,
  OTP_SERVICE_BASE_URL,
  SEND_OTP_URL,
  VERIFY_OTP_URL,
  REQUEST_TIMEOUT_MS,
};
